from typing import Protocol

from .models import (
    CameraForm,
    DefaultOptics,
    DefaultOpticsForm,
    LocationForm,
    ObserverForm,
    RoiForm,
    RoiCenteredForm,
)

from azotea_cli.common.rect import Rect
from azotea_cli.common.reader.models import ImageMetadata

# ----------
# Interfaces
# ----------

class Display(Protocol):
    def display(self, text: str) -> None: ...

class ConsentProv(Protocol):
    def review(self) -> str: ...
    def agree(self, agreed: bool) -> None: ...
    def agreed(self) -> bool: ...
    def check_raises(self) -> None: ...

class LocationProv(Protocol):
    def create(self, form: LocationForm, as_default: bool) -> int: ...
    def update(self, form: LocationForm) -> None: ...
    def set_default(self, location_id) -> None: ...
    def get_default(self) -> int: ...

class OpticsProv(Protocol):
    def save(self, form: DefaultOpticsForm) -> None: ...
    def load(self) -> DefaultOptics: ...

class ObserverProv(Protocol):
    def create_versioned(self, form: ObserverForm, as_default: bool) -> int: ...
    def update(self, form: ObserverForm) -> None: ...
    def set_default(self, observer_id) -> None: ...
    def get_default(self) -> int: ...

class CameraProv(Protocol):
    def create(self, form: CameraForm, as_default: bool) -> int: ...
    def create_from_image(self, metadata: ImageMetadata, as_default: bool) -> int: ...
    def set_default(self, camera_id) -> None: ...
    def get_default(self) -> int: ...

class RoiProv(Protocol):
    def create(self, form: RoiForm, as_default: bool) -> int: ...
    def create_from_image(self,  rect: Rect,  metadata: ImageMetadata, as_default: bool) -> int: ...
    def set_default(self,roi_id) -> None: ...
    def get_default(self) -> int: ...
