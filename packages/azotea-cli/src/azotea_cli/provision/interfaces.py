from typing import Protocol

from azotea_cli.common.models import ObjId
from azotea_cli.common.reader.models import ImageMetadata
from azotea_cli.common.rect import Rect

from .models import (
    CameraForm,
    DefaultOptics,
    DefaultOpticsForm,
    LocationForm,
    ObserverForm,
    RoiForm,
)

# ----------
# Interfaces
# ----------


class Display(Protocol):
    def display(self, text: str) -> None: ...


class ConsentRepo(Protocol):
    def review(self) -> str: ...
    def agree(self, agreed: bool) -> None: ...
    def agreed(self) -> bool: ...
    def check_raises(self) -> None: ...


class LocationRepo(Protocol):
    def create(self, form: LocationForm) -> ObjId: ...
    def update(self, form: LocationForm) -> None: ...
    def set_default(self, location_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...


class OpticsRepo(Protocol):
    def save(self, form: DefaultOpticsForm) -> None: ...
    def load(self) -> DefaultOptics: ...


class ObserverRepo(Protocol):
    def create_versioned(self, form: ObserverForm) -> ObjId: ...
    def update(self, form: ObserverForm) -> None: ...
    def set_default(self, observer_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...
    def get_name(self, observer_id: ObjId) -> tuple[str,str]: ...


class CameraRepo(Protocol):
    def create(self, form: CameraForm) -> ObjId: ...
    def create_from_image(self, metadata: ImageMetadata) -> ObjId: ...
    def set_default(self, camera_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...
    def get_extension_by_id(self, camera_id: ObjId)-> str: ...
    def get_id_by_model(self, model: str) -> ObjId: ...


class RoiRepo(Protocol):
    def create(self, form: RoiForm) -> ObjId: ...
    def create_from_image(self, rect: Rect, metadata: ImageMetadata) -> ObjId: ...
    def set_default(self, roi_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...
    def get_as_rect(self, roi_id: ObjId) -> Rect: ...
