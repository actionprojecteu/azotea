from typing import Protocol

from azotea_cli.common.models import ObjId
from azotea_cli.common.reader.models import ImageMetadata
from azotea_cli.common.rect import Rect

from .models import (
    CameraForm,
    DefaultOptics,
    DefaultOpticsForm,
    LocationForm,
    ObserverForm,
    RoiForm,
)

# ----------
# Interfaces
# ----------


class Display(Protocol):
    def display(self, text: str) -> None: ...


class ConsentProv(Protocol):
    def review(self) -> str: ...
    def agree(self, agreed: bool) -> None: ...
    def agreed(self) -> bool: ...
    def check_raises(self) -> None: ...


class LocationProv(Protocol):
    def create(self, form: LocationForm, as_default: bool) -> ObjId: ...
    def update(self, form: LocationForm) -> None: ...
    def set_default(self, location_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...


class OpticsProv(Protocol):
    def save(self, form: DefaultOpticsForm) -> None: ...
    def load(self) -> DefaultOptics: ...


class ObserverProv(Protocol):
    def create_versioned(self, form: ObserverForm, as_default: bool) -> ObjId: ...
    def update(self, form: ObserverForm) -> None: ...
    def set_default(self, observer_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...


class CameraProv(Protocol):
    def create(self, form: CameraForm, as_default: bool) -> ObjId: ...
    def create_from_image(self, metadata: ImageMetadata, as_default: bool) -> ObjId: ...
    def set_default(self, camera_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...


class RoiProv(Protocol):
    def create(self, form: RoiForm, as_default: bool) -> ObjId: ...
    def create_from_image(self, rect: Rect, metadata: ImageMetadata, as_default: bool) -> ObjId: ...
    def set_default(self, roi_id: ObjId) -> None: ...
    def get_default(self) -> ObjId: ...
