from typing import Protocol
from collections.abc import Sequence
from datetime import datetime

from azotea_cli.common.models import ObjId

from .models import ObservationReport, SummaryTotals, SummaryRanged

class ReportsService(Protocol):
    """Meant to be exported to an external file (i.e CSV("""
    def get_all_data_by(self, observer_id: ObjId) -> Sequence[ObservationReport]: ...
    def get_ranged_data_by(self, observer_id: ObjId, since: datetime, until: datetime) -> Sequence[ObservationReport]: ...
    def get_unpublished_data_by(self, observer_id: ObjId) -> Sequence[ObservationReport]: ...
    def get_latest_night_data_by(self, observer_id: ObjId) -> tuple[Sequence[ObservationReport], datetime]: ...
    def get_latest_month_data_by(self, observer_id: ObjId) -> tuple[Sequence[ObservationReport], datetime]: ...

class SummaryService(Protocol):
    """Meant to be displayed locally on console"""
    def totals_by(self, observer_id: ObjId) ->  Sequence[SummaryTotals]: ...
    def ranged_summary_by(self, observer_id: ObjId) ->  Sequence[SummaryRanged]: ...

class ExporterService(Protocol):
    def export(self, report_name: str, data:Sequence[ObservationReport]) -> None: ...

class DisplayService(Protocol):
    def show_totals(self, data:Sequence[SummaryTotals]) -> None: ...
    def show_ranged_summary(self, data:Sequence[SummaryRanged]) -> None: ...
